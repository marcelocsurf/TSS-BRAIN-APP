 $$# The Four Blue Belt Concepts

The 4 BB Concepts are ==transversal techniques== the student carries across multiple sequences. They are not bound to a single STP.

## 11.1 — Floater

> [!TEACH]
> Explain the mechanic (belly of the board over the foam · cross the section · come down and transition). Demonstrate on a small breaking section. Have the student attempt it on a section that's about to close.

> [!CORRECT]
> Common error: student tries to go AROUND a closing section instead of OVER it. → "Go over the foam · belly of the board on the foam."

> [!CUE]
> "Belly of the board over the foam · cross the section · come down and transition."

## 11.2 — Impulso

> [!TEACH]
> A speed-recovery tool. Reference WB/YB foundational Impulso. Show the two-hands-flexing motion. Tie it to BB scenarios: post-cutback recovery, stuck-on-foam exit.

> [!CORRECT]
> Common error: student doesn't use Impulso when stuck. → "Two hands · flex · propel forward · generate speed."

> [!CUE]
> "Two hands · flex · propel forward · generate speed · maintain momentum."

## 11.3 — Low Finish

> [!TEACH]
> The default closing posture. Demonstrate at the end of every maneuver. Make it the audit point: "Did you land in Low Finish?"

> [!CORRECT]
> Common error: student ends extended after a maneuver. → "Hips down · chest over the knee."

> [!CUE]
> "Hips down · chest over the knee · low finish."

## 11.4 — Bottom Turn (BT) Concept

> [!TEACH]
> Explain the 4 types of BT. Show each on land + skateboard. Have the student verbalize which BT they'll use BEFORE every wave: "This wave I'll use a Long BT because I want to do a Cutback."

| BT Type | When |
|---|---|
| Deep BT | Wave allows full descent (post-BB territory) |
| Mid-Face BT | Standard for snaps (canonized as STP-039) |
| Long BT | Cutbacks (Seq #12/#13) |
| Extended BT | Long-section linking (advanced) |

> [!CORRECT]
