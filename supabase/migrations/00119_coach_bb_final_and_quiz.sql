 $$# BB Exit Test Administration

## 13.1 — Your authority and responsibility

You are authorized to administer the Blue Belt Exit Test at L2 Practitioner level.

> [!CRITICAL]
> Critical difference from the YB Exit Test: the BB student ==SELF-ADMINISTERS== the test using the 3 Questions Framework + the self-evaluation rubric (Student Course §12). Your role is to AUDIT the self-evaluation, not to evaluate from scratch. You confirm or override; if you disagree you have final word — but always start by asking "What did you evaluate? Why?"

## 13.2 — How to administer

Across 3 sessions in varied conditions. Each session: pre-session the student verbalizes their self-evaluation plan; the student executes each sequence 5 times where conditions allow; post-session the student verbalizes results. ==Do NOT correct during the test== — the test is an evaluation, not a teaching session. After all 3 sessions, audit the student's self-evaluation against your observations.

## 13.3 — The 6 sequences · self-thresholds

| Sequence | Self-threshold | Your audit |
|---|---|---|
| Seq #8 Pump FS | 3/5 · speed generation · weight forward · FP3 | Confirm via observation |
| Seq #9 Pump BS | 3/5 · BS body mechanics active | Confirm via observation |
| Seq #10 FS Foundation Chain | 4/5 · Universal Formula complete | Confirm via observation |
| Seq #11 BS Foundation Chain | 4/5 · Separation Rule honored | Confirm via observation |
| Seq #12 FS Linking | 4/5 · single continuous line · return to pocket | Confirm via observation |
| Seq #13 BS Linking | 4/5 · survive foam return | Confirm via observation |

## 13.4 — The Belt Value evaluation

Have the student write/verbalize: "What does Compromiso Consciente mean to me?", a specific personal example of when they wanted to skip a stage and didn't, and their commitment going forward. Audit: is it authentic, specific, personal? If generic or memorized, return them for more time.

## 13.5 — The Big Three disqualifying patterns

> [!CRITICAL]
> If observed consistently during the test, the student is NOT ready: ==Weight drifts backward== · ==Cutback in 2 movements== · ==Skipping a Universal Formula stage==. If any appears on 2+ sequences, return the student to mid-BB practice for ≥4 weeks, then re-test.

## 13.6 — Rubric

| Level | Criteria |
|---|---|
| Acceptable | Meets threshold per sequence · self-corrects within 2 attempts · audit confirms self-evaluation |
| Ideal | Exceeds threshold · self-corrects within 1 attempt · can teach another student something |
| Unacceptable | Below threshold on any sequence · cannot self-identify failed stage · cannot verbalize Belt Value authentically |

## 13.7 — Minimum sessions and re-test policy

Minimum 12 sessions at BB level before the Exit Test. If FAIL → specific remediation plan · re-test minimum 4 weeks later. If PASS → Blue Belt certificate issued · Purple Belt onboarding scheduled.

> [!MANTRA]
> The Blue Belt Exit Test is a structural commitment test, not a maneuver test. The question: "Has this student internalized the Universal Sequence Formula as their default operating mode?" If yes → graduate. If no → return them for more time. "There are no shortcuts. They have to walk the path."

