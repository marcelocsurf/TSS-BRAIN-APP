## 14 — Coach Code of Conduct

As a TSS L2 Practitioner Coach teaching Blue Belt, you commit to: ==Doctrinal fidelity== (teach the Universal Formula as canonized; no variations from other systems) · ==Compromiso Consciente in your own practice== (no modeled shortcuts) · ==Safety override always== · ==Confidentiality of student data== · ==Honest assessment== (don't graduate students who haven't earned it) · ==Stance discipline== (actively step back; don't regress out of habit) · ==Universal Formula language== (no generic feedback) · ==3 Questions Framework== (audit after every session) · ==No personal style imposition== (style emerges at Purple Belt) · ==Continuous formation== (annual L2 recertification).

> [!CRITICAL]
> Failure to honor this code is grounds for certification suspension or revocation per Core Canon §D.10.

## 15 — Appendix A: Error Taxonomy

> [!MANTRA]
> "An error is not a failure — it is a diagnostic signal. The error tells you which stage of the Universal Formula needs work. At Blue Belt, you audit the student's self-identification of errors."

The Big Three at BB: ==Weight drifts backward== (most common · loses speed) · ==Cutback in 2 movements== (Hold failure) · ==Skipping a Universal Formula stage== (breaks structural commitment).

How to use the taxonomy in a session: observe the attempt → identify which STAGE failed → identify the specific ERROR → ask "Which stage failed? Why?" → if correct, confirm + suggest a drill; if incorrect, name the actual failure + explain → set the next mission targeting that error → confirm self-correction on the next attempt.

> [!DOCTRINE]
> Full 86-row catalog with immediate-correction language lives in the Belt Master Registry (BB_ERROR_TAXONOMY).

## 16 — Appendix B: Glossary (selected)

- **Universal Sequence Formula** — the 6-stage architecture of every BB maneuver: Posture → Rotation → Projection → Maneuver → Closure → Posture.
- **Compromiso Consciente** — Conscious Commitment · BB Belt Value · structural commitment to honoring the Universal Formula.
- **FP1 / FP2 / FP3** — Foot Positions 1 (tail) · 2 (center) · 3 (forward). **Press the Button** — the dynamic action of transitioning the back foot between FPs.
- **Cruz** — FS body position: palms forward · chest open · oblique engaged · rail change. **Cruz Snap** (STP-041) · **Cruz Cutback** (STP-046).
- **Hold** — sustained position to save energy · the H of P·R·C·H · operationalized at Seq #12. **Hold Rotation** — BS equivalent (STP-049).
- **Choke** (STP-043) — BS projection, cross-arm + leg extension. **Tapaloco Snap** (STP-044) — BS rail change, 4 variants with HAND ideal. **Tapaloco Cutback** (STP-048).
- **Grenade** (STP-042) — FS closure. **Codazo / Elbow** (STP-045) — BS closure, elbow up + scapulas united.
- **Separation Rule** — Choke = setup · Tapaloco = rail change · Elbow = throw water.
- **Three Circles of Power** — BODY (P·R·C·H) · BOARD (FP) · WAVE. **Infinite Circle** — continuous execution loop within the wave.
- **Audit/Refinement stance (BB)** — the L2 Practitioner Coach operational stance: auditor/refiner; the student is operationally independent.

